    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String StockID = StockId.getText().trim();

        if (StockID.isBlank()) {
            JOptionPane.showMessageDialog(null,
                    "Please Enter The Stock Id",
                    "Stock managment",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            ResultSet rs = connection.Search("SELECT * FROM `stock` WHERE `stock`.`Stock_ID` = '" + StockID + "'");

            if (rs.next()) {

                int StatusId;
                String status;

                if (rs.getInt("S_status") == 1) {
                    StatusId = 0;
                    status = "Deactivated";
                } else {
                    StatusId = 1;
                    status = "Activated";
                }

                connection.IUD("UPDATE `stock` SET `S_status` = '" + StatusId + "' WHERE `stock`.`Stock_ID` = '" + StockID + "'");

                JOptionPane.showMessageDialog(null,
                        "Stock Has Been" + status,
                        "Stock managment",
                        JOptionPane.PLAIN_MESSAGE);
                LoadTable();
                SearchTable();

            } else {
                JOptionPane.showMessageDialog(null,
                        "Please Enter The Correct ID",
                        "Stock managment",
                        JOptionPane.ERROR_MESSAGE);
            }

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(null,
                    "Please Contact The Devoloper",
                    "Stock managment",
                    JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton1ActionPerformed


