    private void LoadTable() {

        try {
            ResultSet rs = connection.Search("SELECT * FROM `stock` "
                    + "INNER JOIN `books` ON `stock`.`S_Book_id` = `books`.`Book_id` "
                    + "INNER JOIN `status` ON `stock`.`S_status` = `status`.`Status_ID`");
            DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
            dtm.setRowCount(0);

            while (rs.next()) {
                Vector<String> v = new Vector<>();
                v.add(rs.getString("Stock_ID"));
                v.add(rs.getString("Book_Name"));
                v.add(rs.getString("Original_Price"));
                v.add(rs.getString("Public_Price"));
                v.add(rs.getString("Qty"));
                v.add(rs.getString("Sold"));
                v.add(rs.getString("Last_Stock_Update"));
                v.add(rs.getString("status"));
                dtm.addRow(v);

            }

        } catch (java.sql.SQLException e) {
            e.printStackTrace();
        }

    }

    private void SearchTable() {

        String StockID = StockId.getText().trim();

        if (StockID.isBlank()) {
            LoadTable();
        } else {

            try {
                ResultSet rs = connection.Search("SELECT * FROM `stock` "
                        + "INNER JOIN `books` ON `stock`.`S_Book_id` = `books`.`Book_id` "
                        + "INNER JOIN `status` ON `stock`.`S_status` = `status`.`Status_ID` WHERE `stock`.`Stock_ID` LIKE '%" + StockID + "%'");
                DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
                dtm.setRowCount(0);

                while (rs.next()) {
                    Vector<String> v = new Vector<>();
                    v.add(rs.getString("Stock_ID"));
                    v.add(rs.getString("Book_Name"));
                    v.add(rs.getString("Original_Price"));
                    v.add(rs.getString("Public_Price"));
                    v.add(rs.getString("Qty"));
                    v.add(rs.getString("Sold"));
                    v.add(rs.getString("Last_Stock_Update"));
                    v.add(rs.getString("status"));
                    dtm.addRow(v);

                    if (rs.getInt("S_status") == 1) {
                        jButton1.setText("Deactivate Stock");
                        jButton1.setBackground(Color.red);
                    } else {
                        jButton1.setText("Activate Stock");
                        jButton1.setBackground(Color.green);
                    }

                }

            } catch (java.sql.SQLException e) {
                e.printStackTrace();
            }
        }
    }

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        LoadTable();
        try {
            InputStream filePath = getClass()
                    .getClassLoader()
                    .getResourceAsStream("booksmart/Report/Booksmart_Stock.jasper");
            HashMap<String, Object> parameters = new HashMap<>();

            JRTableModelDataSource jrTableModelDataSource = new JRTableModelDataSource(jTable1.getModel());
            JasperPrint fillReport = JasperFillManager.fillReport(filePath, parameters, jrTableModelDataSource);
            JasperViewer.viewReport(fillReport, false);
        } catch (JRException e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton2ActionPerformed

